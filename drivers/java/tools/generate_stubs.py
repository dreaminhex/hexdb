#!/usr/bin/env python3
"""Generate the Unsupported* base classes of the JDBC driver.

Each java.sql interface the driver implements gets a package-private
abstract class with every abstract method of the interface: the driver's
classes extend it and override what HexDB supports. The rest throw
SQLFeatureNotSupportedException naming the method, except metadata
questions (DatabaseMetaData), which answer conservatively (false, 0, an
empty string, or an empty result set with the standard columns).

Run with javap output from the oldest JDK the driver supports (11):

    for c in Driver Connection Statement PreparedStatement ResultSet ResultSetMetaData DatabaseMetaData; do
        javap java.sql.$c > javap/$c.txt
    done
    python3 tools/generate_stubs.py javap

The generated files are committed; regenerate when the supported JDK changes.
"""
import re
import sys
from pathlib import Path

INTERFACES = ["Driver", "Connection", "Statement", "PreparedStatement", "ResultSet", "ResultSetMetaData", "DatabaseMetaData"]
# PreparedStatement's base extends the driver's Statement, which implements Statement's methods.
PARENT = {"PreparedStatement": "HexDBStatement"}
OUT = Path(__file__).resolve().parent.parent / "src" / "main" / "java" / "com" / "dreaminhex" / "hexdb" / "jdbc"
METHOD = re.compile(r"^\s+public abstract (?:(<[^>]+>) )?(.+) (\w+)\((.*)\)(?: throws (.+))?;$")


def split_args(text):
    args, depth, current = [], 0, ""
    for c in text:
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        if c == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += c
    if current.strip():
        args.append(current.strip())
    return args


def body(interface, returns, name, throws):
    declared = [t.strip() for t in (throws or "").split(",") if t.strip()]
    if "java.sql.SQLException" not in declared and "java.sql.SQLFeatureNotSupportedException" not in declared:
        # The method can't throw SQLException: use what it declares, or an unchecked exception.
        if "java.sql.SQLClientInfoException" in declared:
            return f'throw new java.sql.SQLClientInfoException("{interface}.{name} is not supported by the HexDB driver.", null);'
        return f'throw new UnsupportedOperationException("{interface}.{name} is not supported by the HexDB driver.");'
    if interface == "DatabaseMetaData":
        if returns == "boolean":
            return "return false;"
        if returns in ("int", "long"):
            return "return 0;"
        if returns == "java.lang.String":
            return 'return "";'
        if returns == "java.sql.ResultSet":
            return f'return empty("{name}");'
        if returns == "java.sql.RowIdLifetime":
            return "return java.sql.RowIdLifetime.ROWID_UNSUPPORTED;"
    return f'throw Unsupported.feature("{interface}.{name}");'


def generate(interface, javap):
    lines = []
    for line in javap.splitlines():
        m = METHOD.match(line)
        if not m:
            continue
        generic, returns, name, args, throws = m.groups()
        params = ", ".join(f"{t} a{i}" for i, t in enumerate(split_args(args)))
        head = f"    public {generic + ' ' if generic else ''}{returns} {name}({params})"
        if throws:
            head += f" throws {throws}"
        lines.append(f"{head} {{\n        {body(interface, returns, name, throws)}\n    }}\n")
    parent = PARENT.get(interface)
    extends = f"extends {parent} " if parent else ""
    wrapper = ""
    if interface != "Driver" and not parent:
        wrapper = """    public <T> T unwrap(Class<T> type) throws java.sql.SQLException {
        if (type.isInstance(this)) {
            return type.cast(this);
        }
        throw new java.sql.SQLException("Not a wrapper for " + type.getName() + ".");
    }

    public boolean isWrapperFor(Class<?> type) {
        return type.isInstance(this);
    }

"""
    extra = ""
    if interface == "DatabaseMetaData":
        extra = "    /** An empty result with the standard columns of a metadata method. */\n    protected abstract java.sql.ResultSet empty(String method) throws java.sql.SQLException;\n\n"
    if parent:
        constructor = f"    Unsupported{interface}(HexDBConnection connection) {{\n        super(connection);\n    }}\n\n"
    else:
        constructor = ""
    return (
        f"// Generated by drivers/java/tools/generate_stubs.py from JDK 11's java.sql.{interface}. Don't edit.\n"
        "package com.dreaminhex.hexdb.jdbc;\n\n"
        f"/** Every method of {interface} that HexDB's driver doesn't override. */\n"
        '@SuppressWarnings("deprecation") // the interface\'s deprecated methods still need bodies\n'
        f"abstract class Unsupported{interface} {extends}implements java.sql.{interface} {{\n"
        + constructor
        + extra
        + wrapper
        + "\n".join(lines)
        + "}\n"
    )


def main():
    source = Path(sys.argv[1])
    for interface in INTERFACES:
        javap = (source / f"{interface}.txt").read_text(encoding="utf-8")
        (OUT / f"Unsupported{interface}.java").write_text(generate(interface, javap), encoding="utf-8", newline="\n")
        print("wrote", f"Unsupported{interface}.java")


if __name__ == "__main__":
    main()
