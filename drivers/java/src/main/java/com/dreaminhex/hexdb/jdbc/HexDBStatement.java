package com.dreaminhex.hexdb.jdbc;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.util.List;
import java.util.Map;

/** A statement: runs SQL (SELECT, or DELETE ... WHERE) through POST /sql. */
public class HexDBStatement extends UnsupportedStatement {
    final HexDBConnection connection;
    private HexDBResultSet result;
    /** The last DELETE's count of deleted rows; -1 after a query or once read past. */
    private long updateCount = -1;
    private boolean closed;
    private boolean closeOnCompletion;
    private long maxRows;
    private int fetchSize;
    private int queryTimeout;
    private boolean escapes = true;

    HexDBStatement(HexDBConnection connection) {
        this.connection = connection;
    }

    void check() throws SQLException {
        if (closed) {
            throw Unsupported.closed("statement");
        }
        connection.check();
    }

    String prepare(String sql) {
        return escapes ? Escapes.rewrite(sql) : sql;
    }

    /** True for a DELETE statement (after leading spaces, comments and parentheses). */
    static boolean isDelete(String sql) {
        int i = 0;
        int n = sql.length();
        while (i < n) {
            char c = sql.charAt(i);
            if (Character.isWhitespace(c) || c == '(') {
                i++;
            } else if (sql.startsWith("--", i)) {
                int end = sql.indexOf('\n', i);
                i = end < 0 ? n : end + 1;
            } else if (sql.startsWith("/*", i)) {
                int end = sql.indexOf("*/", i + 2);
                i = end < 0 ? n : end + 2;
            } else {
                break;
            }
        }
        if (!sql.regionMatches(true, i, "DELETE", 0, 6)) {
            return false;
        }
        return i + 6 == n || !Character.isLetterOrDigit(sql.charAt(i + 6)) && sql.charAt(i + 6) != '_';
    }

    private void reset() {
        if (result != null) {
            result.discard();
            result = null;
        }
        updateCount = -1;
    }

    /** Run a query and keep its result. */
    HexDBResultSet run(String sql, List<Object> params) throws SQLException {
        check();
        if (isDelete(sql)) {
            throw new SQLException("executeQuery needs a statement that returns rows; run a DELETE with executeUpdate or execute.", "07000");
        }
        reset();
        return query(sql, params);
    }

    /** Run a DELETE; returns how many rows it deleted. */
    long update(String sql, List<Object> params) throws SQLException {
        check();
        if (!isDelete(sql)) {
            throw new SQLException("executeUpdate runs DELETE statements (HexDB's SQL writes nothing else); run a SELECT with executeQuery.", "07000");
        }
        reset();
        Map<String, Object> answer = connection.client.sql(sql, params, null, connection.client.pageSize);
        Object affected = answer.get("rows_affected");
        updateCount = affected instanceof Number ? ((Number) affected).longValue() : 0;
        return updateCount;
    }

    /** Run either; true when there's a result set (JDBC's execute). */
    boolean any(String sql, List<Object> params) throws SQLException {
        if (isDelete(sql)) {
            update(sql, params);
            return false;
        }
        run(sql, params);
        return true;
    }

    private HexDBResultSet query(String sql, List<Object> params) throws SQLException {
        Client client = connection.client;
        int size = fetchSize > 0 ? Math.min(fetchSize, Client.MAX_PAGE_SIZE) : client.pageSize;
        if (maxRows > 0 && maxRows < size) {
            size = (int) maxRows;
        }
        int pageSize = size;
        Map<String, Object> first = client.sql(sql, params, null, pageSize);
        result = new HexDBResultSet(this, first, cursor -> client.sql(sql, params, cursor, pageSize), maxRows);
        result.setFetchSize(fetchSize);
        return result;
    }

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        return run(prepare(sql), List.of());
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        return any(prepare(sql), List.of());
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return execute(sql);
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        return (int) Math.min(update(prepare(sql), List.of()), Integer.MAX_VALUE);
    }

    @Override
    public long executeLargeUpdate(String sql) throws SQLException {
        return update(prepare(sql), List.of());
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        if (autoGeneratedKeys != NO_GENERATED_KEYS) {
            throw Unsupported.feature("generated keys");
        }
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        throw Unsupported.feature("generated keys");
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        throw Unsupported.feature("generated keys");
    }

    @Override
    public ResultSet getResultSet() throws SQLException {
        check();
        return result;
    }

    @Override
    public int getUpdateCount() throws SQLException {
        check();
        return (int) Math.min(updateCount, Integer.MAX_VALUE);
    }

    @Override
    public long getLargeUpdateCount() throws SQLException {
        check();
        return updateCount;
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        check();
        reset();
        return false;
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        return getMoreResults();
    }

    void resultClosed() throws SQLException {
        if (closeOnCompletion && !closed) {
            close();
        }
    }

    @Override
    public void close() throws SQLException {
        if (closed) {
            return;
        }
        closed = true;
        if (result != null) {
            HexDBResultSet r = result;
            result = null;
            r.close();
        }
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        check();
        closeOnCompletion = true;
    }

    @Override
    public boolean isCloseOnCompletion() throws SQLException {
        check();
        return closeOnCompletion;
    }

    @Override
    public Connection getConnection() throws SQLException {
        check();
        return connection;
    }

    @Override
    public int getMaxRows() throws SQLException {
        check();
        return (int) Math.min(maxRows, Integer.MAX_VALUE);
    }

    @Override
    public void setMaxRows(int max) throws SQLException {
        setLargeMaxRows(max);
    }

    @Override
    public long getLargeMaxRows() throws SQLException {
        check();
        return maxRows;
    }

    @Override
    public void setLargeMaxRows(long max) throws SQLException {
        check();
        if (max < 0) {
            throw new SQLException("maxRows can't be negative.", "HY024");
        }
        maxRows = max;
    }

    @Override
    public int getFetchSize() throws SQLException {
        check();
        return fetchSize;
    }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        check();
        if (rows < 0) {
            throw new SQLException("The fetch size can't be negative.", "HY024");
        }
        fetchSize = rows;
    }

    @Override
    public int getFetchDirection() {
        return ResultSet.FETCH_FORWARD;
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        if (direction != ResultSet.FETCH_FORWARD) {
            throw Unsupported.feature("Statement.setFetchDirection (only FETCH_FORWARD)");
        }
    }

    @Override
    public int getQueryTimeout() throws SQLException {
        check();
        return queryTimeout;
    }

    /** Recorded; the connection's timeout (the timeout property) applies to each request. */
    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        check();
        if (seconds < 0) {
            throw new SQLException("The timeout can't be negative.", "HY024");
        }
        queryTimeout = seconds;
    }

    @Override
    public void setEscapeProcessing(boolean enable) throws SQLException {
        check();
        escapes = enable;
    }

    @Override
    public int getMaxFieldSize() throws SQLException {
        check();
        return 0;
    }

    @Override
    public void setMaxFieldSize(int max) throws SQLException {
        check();
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        check();
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public int getResultSetType() {
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getResultSetConcurrency() {
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetHoldability() {
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public boolean isPoolable() {
        return false;
    }

    @Override
    public void setPoolable(boolean poolable) {
    }

    @Override
    public void cancel() throws SQLException {
        check();
        // Each page is one short request; there's nothing running to cancel between them.
    }
}
