package com.dreaminhex.hexdb.jdbc;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.HashMap;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * A connection to a HexDB server. HexDB's SQL is read-only, so there are no
 * transactions: autocommit, commit and rollback are accepted and do nothing.
 */
public class HexDBConnection extends UnsupportedConnection {
    final Client client;
    private volatile boolean closed;
    private final Properties clientInfo = new Properties();

    HexDBConnection(Client client) {
        this.client = client;
    }

    void check() throws SQLException {
        if (closed) {
            throw Unsupported.closed("connection");
        }
    }

    private static void plain(int type, int concurrency) throws SQLException {
        if (type != ResultSet.TYPE_FORWARD_ONLY || concurrency != ResultSet.CONCUR_READ_ONLY) {
            throw Unsupported.feature("result sets other than forward-only, read-only");
        }
    }

    @Override
    public Statement createStatement() throws SQLException {
        check();
        return new HexDBStatement(this);
    }

    @Override
    public Statement createStatement(int type, int concurrency) throws SQLException {
        plain(type, concurrency);
        return createStatement();
    }

    @Override
    public Statement createStatement(int type, int concurrency, int holdability) throws SQLException {
        plain(type, concurrency);
        return createStatement();
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        check();
        return new HexDBPreparedStatement(this, sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int type, int concurrency) throws SQLException {
        plain(type, concurrency);
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int type, int concurrency, int holdability) throws SQLException {
        plain(type, concurrency);
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public String nativeSQL(String sql) throws SQLException {
        check();
        return Escapes.rewrite(sql);
    }

    @Override
    public DatabaseMetaData getMetaData() throws SQLException {
        check();
        return new HexDBDatabaseMetaData(this);
    }

    // -- Transactions: none (read-only) ----------------------------------------

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException {
        check();
    }

    @Override
    public boolean getAutoCommit() throws SQLException {
        check();
        return true;
    }

    @Override
    public void commit() throws SQLException {
        check();
    }

    @Override
    public void rollback() throws SQLException {
        check();
    }

    @Override
    public void setReadOnly(boolean readOnly) throws SQLException {
        check();
    }

    @Override
    public boolean isReadOnly() throws SQLException {
        check();
        return true;
    }

    @Override
    public void setTransactionIsolation(int level) throws SQLException {
        check();
    }

    @Override
    public int getTransactionIsolation() throws SQLException {
        check();
        return Connection.TRANSACTION_NONE;
    }

    @Override
    public int getHoldability() throws SQLException {
        check();
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public void setHoldability(int holdability) throws SQLException {
        check();
    }

    // -- Catalogs and schemas: HexDB has neither ---------------------------------

    @Override
    public void setCatalog(String catalog) throws SQLException {
        check();
    }

    @Override
    public String getCatalog() throws SQLException {
        check();
        return null;
    }

    @Override
    public void setSchema(String schema) throws SQLException {
        check();
    }

    @Override
    public String getSchema() throws SQLException {
        check();
        return null;
    }

    @Override
    public Map<String, Class<?>> getTypeMap() throws SQLException {
        check();
        return new HashMap<>();
    }

    @Override
    public void setTypeMap(Map<String, Class<?>> map) throws SQLException {
        check();
    }

    // -- The connection itself -----------------------------------------------

    @Override
    public void close() {
        closed = true;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void abort(Executor executor) {
        closed = true;
    }

    @Override
    public boolean isValid(int timeout) throws SQLException {
        if (timeout < 0) {
            throw new SQLException("The timeout can't be negative.", "HY024");
        }
        return !closed && client.healthy();
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        check();
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public void setClientInfo(String name, String value) throws SQLClientInfoException {
        if (value == null) {
            clientInfo.remove(name);
        } else {
            clientInfo.setProperty(name, value);
        }
    }

    @Override
    public void setClientInfo(Properties properties) {
        clientInfo.clear();
        if (properties != null) {
            clientInfo.putAll(properties);
        }
    }

    @Override
    public String getClientInfo(String name) {
        return clientInfo.getProperty(name);
    }

    @Override
    public Properties getClientInfo() {
        Properties copy = new Properties();
        copy.putAll(clientInfo);
        return copy;
    }

    @Override
    public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException {
        check();
    }

    @Override
    public int getNetworkTimeout() throws SQLException {
        check();
        return 0;
    }
}
